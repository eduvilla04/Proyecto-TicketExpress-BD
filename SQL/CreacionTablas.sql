-- Categoria

CREATE TABLE categoria (
    id_categoria INT GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR(100) NOT NULL,

    CONSTRAINT pk_categoria
        PRIMARY KEY (id_categoria),

    CONSTRAINT uq_categoria_nombre
        UNIQUE (nombre),

    CONSTRAINT chk_categoria_nombre
        CHECK (LENGTH(TRIM(nombre)) > 0)
);

-- Organizador

CREATE TABLE organizador (
    id_organizador INT GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR(255) NOT NULL,
    telefono VARCHAR(20),
    correo VARCHAR(255),

    CONSTRAINT pk_organizador
        PRIMARY KEY (id_organizador),

    CONSTRAINT uq_organizador_correo
        UNIQUE (correo),

    CONSTRAINT chk_organizador_nombre
        CHECK (LENGTH(BTRIM(nombre)) > 0),

    CONSTRAINT chk_organizador_telefono
        CHECK (
            telefono IS NULL OR
            telefono ~ '^[+]?[0-9]{8,15}$'
        ),

    CONSTRAINT chk_organizador_correo
        CHECK (
            correo IS NULL OR
            correo ~* '^[A-Z0-9._%+-]+@[A-Z0-9.-]+[.][A-Z]{2,}$'
        )
);

--Recinto

CREATE TABLE recinto (
    id_recinto INT GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR(255) NOT NULL,
    ubicacion VARCHAR(255) NOT NULL,

    CONSTRAINT pk_recinto
        PRIMARY KEY (id_recinto),

    CONSTRAINT uq_recinto_nombre_ubicacion
        UNIQUE (nombre, ubicacion),

    CONSTRAINT chk_recinto_nombre
        CHECK (LENGTH(BTRIM(nombre)) > 0),

    CONSTRAINT chk_recinto_ubicacion
        CHECK (LENGTH(BTRIM(ubicacion)) > 0)
);

--Usuario

CREATE TABLE usuario (
    id_usuario INT GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR(255) NOT NULL,
    apellido VARCHAR(255) NOT NULL,
    telefono VARCHAR(20),
    correo VARCHAR(255) NOT NULL,

    CONSTRAINT pk_usuario
        PRIMARY KEY (id_usuario),

    CONSTRAINT uq_usuario_correo
        UNIQUE (correo),

    CONSTRAINT chk_usuario_nombre
        CHECK (LENGTH(BTRIM(nombre)) > 0),

    CONSTRAINT chk_usuario_apellido
        CHECK (LENGTH(BTRIM(apellido)) > 0),

    CONSTRAINT chk_usuario_telefono
        CHECK (
            telefono IS NULL OR
            telefono ~ '^[+]?[0-9]{8,15}$'
        ),

    CONSTRAINT chk_usuario_correo
        CHECK (
            correo ~* '^[A-Z0-9._%+-]+@[A-Z0-9.-]+[.][A-Z]{2,}$'
        )
);

--Evento

CREATE TABLE evento (
    id_evento INT GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR(255) NOT NULL,
    descripcion VARCHAR(500),
    id_organizador INT NOT NULL,
    id_categoria INT NOT NULL,

    CONSTRAINT pk_evento
        PRIMARY KEY (id_evento),

    CONSTRAINT fk_evento_organizador
        FOREIGN KEY (id_organizador)
        REFERENCES organizador (id_organizador),

    CONSTRAINT fk_evento_categoria
        FOREIGN KEY (id_categoria)
        REFERENCES categoria (id_categoria),

    CONSTRAINT chk_evento_nombre
        CHECK (LENGTH(BTRIM(nombre)) > 0),

    CONSTRAINT chk_evento_descripcion
        CHECK (
            descripcion IS NULL OR
            LENGTH(BTRIM(descripcion)) > 0
        )
);

--Zona

CREATE TABLE zona (
    id_zona INT GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR(100) NOT NULL,
    capacidad INT NOT NULL,
    id_recinto INT NOT NULL,

    CONSTRAINT pk_zona
        PRIMARY KEY (id_zona),

    CONSTRAINT fk_zona_recinto
        FOREIGN KEY (id_recinto)
        REFERENCES recinto (id_recinto),

    CONSTRAINT uq_zona_recinto_nombre
        UNIQUE (id_recinto, nombre),

    CONSTRAINT chk_zona_nombre
        CHECK (LENGTH(BTRIM(nombre)) > 0),

    CONSTRAINT chk_zona_capacidad
        CHECK (capacidad > 0)
);

--Funcion

CREATE TABLE funcion (
    id_funcion INT GENERATED BY DEFAULT AS IDENTITY,
    fecha DATE NOT NULL,
    hora TIME NOT NULL,
    estado VARCHAR(30) NOT NULL DEFAULT 'programada',
    id_evento INT NOT NULL,
    id_recinto INT NOT NULL,

    CONSTRAINT pk_funcion
        PRIMARY KEY (id_funcion),

    CONSTRAINT fk_funcion_evento
        FOREIGN KEY (id_evento)
        REFERENCES evento (id_evento),

    CONSTRAINT fk_funcion_recinto
        FOREIGN KEY (id_recinto)
        REFERENCES recinto (id_recinto),

    CONSTRAINT uq_funcion_programacion
        UNIQUE (id_evento, id_recinto, fecha, hora),

    CONSTRAINT chk_funcion_estado
        CHECK (
            estado IN (
                'programada',
                'suspendida',
                'cancelada',
                'finalizada'
            )
        )
);

--Asiento

CREATE TABLE asiento (
    id_asiento INT GENERATED BY DEFAULT AS IDENTITY,
    numero INT NOT NULL,
    fila VARCHAR(10) NOT NULL,
    id_zona INT NOT NULL,

    CONSTRAINT pk_asiento
        PRIMARY KEY (id_asiento),

    CONSTRAINT fk_asiento_zona
        FOREIGN KEY (id_zona)
        REFERENCES zona (id_zona),

    CONSTRAINT uq_asiento_zona_fila_numero
        UNIQUE (id_zona, fila, numero),

    CONSTRAINT chk_asiento_numero
        CHECK (numero > 0),

    CONSTRAINT chk_asiento_fila
        CHECK (LENGTH(BTRIM(fila)) > 0)
);

--Pago

CREATE TABLE pago (
    id_pago INT GENERATED BY DEFAULT AS IDENTITY,
    fecha_pago TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    monto_total DECIMAL(10,2) NOT NULL,
    metodo_pago VARCHAR(50) NOT NULL,
    estado_pago VARCHAR(30) NOT NULL DEFAULT 'pendiente',
    id_usuario INT NOT NULL,

    CONSTRAINT pk_pago
        PRIMARY KEY (id_pago),

    CONSTRAINT fk_pago_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES usuario (id_usuario),

    CONSTRAINT chk_pago_monto
        CHECK (monto_total > 0),

    CONSTRAINT chk_pago_metodo
        CHECK (
            metodo_pago IN (
                'tarjeta',
                'transferencia',
                'efectivo'
            )
        ),

    CONSTRAINT chk_pago_estado
        CHECK (
            estado_pago IN (
                'pendiente',
                'aprobado',
                'rechazado',
                'reembolsado'
            )
        )
);

--Tarifa

CREATE TABLE tarifa (
    id_tarifa INT GENERATED BY DEFAULT AS IDENTITY,
    precio DECIMAL(10,2) NOT NULL,
    id_funcion INT NOT NULL,
    id_zona INT NOT NULL,

    CONSTRAINT pk_tarifa
        PRIMARY KEY (id_tarifa),

    CONSTRAINT fk_tarifa_funcion
        FOREIGN KEY (id_funcion)
        REFERENCES funcion (id_funcion),

    CONSTRAINT fk_tarifa_zona
        FOREIGN KEY (id_zona)
        REFERENCES zona (id_zona),

    CONSTRAINT uq_tarifa_funcion_zona
        UNIQUE (id_funcion, id_zona),

    CONSTRAINT uq_tarifa_id_funcion
        UNIQUE (id_tarifa, id_funcion),

    CONSTRAINT chk_tarifa_precio
        CHECK (precio > 0)
);

--Tique

CREATE TABLE tique (
    codigo_tique VARCHAR(50) NOT NULL,
    precio DECIMAL(10,2) NOT NULL,
    id_pago INT NOT NULL,
    id_asiento INT NOT NULL,
    id_funcion INT NOT NULL,
    id_tarifa INT NOT NULL,

    CONSTRAINT pk_tique
        PRIMARY KEY (codigo_tique),

    CONSTRAINT fk_tique_pago
        FOREIGN KEY (id_pago)
        REFERENCES pago (id_pago),

    CONSTRAINT fk_tique_asiento
        FOREIGN KEY (id_asiento)
        REFERENCES asiento (id_asiento),

    CONSTRAINT fk_tique_funcion
        FOREIGN KEY (id_funcion)
        REFERENCES funcion (id_funcion),

    CONSTRAINT fk_tique_tarifa_funcion
        FOREIGN KEY (id_tarifa, id_funcion)
        REFERENCES tarifa (id_tarifa, id_funcion),

    CONSTRAINT uq_tique_funcion_asiento
        UNIQUE (id_funcion, id_asiento),

    CONSTRAINT chk_tique_codigo
        CHECK (LENGTH(BTRIM(codigo_tique)) > 0),

    CONSTRAINT chk_tique_precio
        CHECK (precio > 0)
);
