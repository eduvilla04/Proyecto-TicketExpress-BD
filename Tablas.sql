-- CREACION DE TABLAS
-- ==========================================


-- 1. CATEGORIA

CREATE TABLE categoria (
    idcategoria BIGINT GENERATED BY DEFAULT AS IDENTITY,
    categoria VARCHAR(100) NOT NULL,

    CONSTRAINT pk_categoria
        PRIMARY KEY (idcategoria),

    CONSTRAINT uq_categoria
        UNIQUE (categoria),

    CONSTRAINT chk_categoria
        CHECK (TRIM(categoria) <> '')
);


-- 2. RECINTO

CREATE TABLE recinto (
    idrecinto BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR(255) NOT NULL,
    direccion VARCHAR(255) NOT NULL,
    ciudad VARCHAR(100) NOT NULL,
    capacidadTotal INT NOT NULL,

    CONSTRAINT pk_recinto
        PRIMARY KEY (idrecinto),

    CONSTRAINT chk_recinto_capacidad
        CHECK (capacidadTotal > 0)
);


-- 3. USUARIO

CREATE TABLE usuario (
    idusuario BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR(100) NOT NULL,
    apellido VARCHAR(100) NOT NULL,
    correo VARCHAR(255) NOT NULL,
    telefono VARCHAR(20),
    usuario VARCHAR(100) NOT NULL,
    clave VARCHAR(255) NOT NULL,
    fechaRegistro DATE NOT NULL DEFAULT CURRENT_DATE,
    estado VARCHAR(30) NOT NULL,

    CONSTRAINT pk_usuario
        PRIMARY KEY (idusuario),

    CONSTRAINT uq_usuario_correo
        UNIQUE (correo),

    CONSTRAINT uq_usuario_nombre
        UNIQUE (usuario),

    CONSTRAINT chk_usuario_clave
        CHECK (TRIM(clave) <> '')
);


-- 4. EVENTO

CREATE TABLE evento (
    idevento BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR(255) NOT NULL,
    descripcion VARCHAR(500),
    idcategoria BIGINT NOT NULL,

    CONSTRAINT pk_evento
        PRIMARY KEY (idevento),

    CONSTRAINT fk_evento_categoria
        FOREIGN KEY (idcategoria)
        REFERENCES categoria(idcategoria)
);


-- 5. ASIENTO

CREATE TABLE asiento (
    idasiento BIGINT GENERATED BY DEFAULT AS IDENTITY,
    fila VARCHAR(10) NOT NULL,
    numero VARCHAR(10) NOT NULL,
    zona VARCHAR(100) NOT NULL,
    idrecinto BIGINT NOT NULL,

    CONSTRAINT pk_asiento
        PRIMARY KEY (idasiento),

    CONSTRAINT fk_asiento_recinto
        FOREIGN KEY (idrecinto)
        REFERENCES recinto(idrecinto),

    CONSTRAINT uq_asiento_ubicacion
        UNIQUE (idrecinto, zona, fila, numero)
);


-- 6. FUNCION

CREATE TABLE funcion (
    idfuncion BIGINT GENERATED BY DEFAULT AS IDENTITY,
    fecha DATE NOT NULL,
    hora TIME NOT NULL,
    idevento BIGINT NOT NULL,
    idrecinto BIGINT NOT NULL,
    estado VARCHAR(30) NOT NULL,

    CONSTRAINT pk_funcion
        PRIMARY KEY (idfuncion),

    CONSTRAINT fk_funcion_evento
        FOREIGN KEY (idevento)
        REFERENCES evento(idevento),

    CONSTRAINT fk_funcion_recinto
        FOREIGN KEY (idrecinto)
        REFERENCES recinto(idrecinto)
);


-- 7. PAGO

CREATE TABLE pago (
    idpago BIGINT GENERATED BY DEFAULT AS IDENTITY,
    fecha DATE NOT NULL,
    hora TIME NOT NULL,
    montoTotal DECIMAL(10,2) NOT NULL,
    metodoPago VARCHAR(50) NOT NULL,
    estado VARCHAR(30) NOT NULL,
    idusuario BIGINT NOT NULL,

    CONSTRAINT pk_pago
        PRIMARY KEY (idpago),

    CONSTRAINT fk_pago_usuario
        FOREIGN KEY (idusuario)
        REFERENCES usuario(idusuario),

    CONSTRAINT chk_pago_monto
        CHECK (montoTotal > 0)
);


-- 8. TARIFA

CREATE TABLE tarifa (
    idtarifa BIGINT GENERATED BY DEFAULT AS IDENTITY,
    precio DECIMAL(10,2) NOT NULL,
    estado VARCHAR(30) NOT NULL,
    idfuncion BIGINT NOT NULL,
    idasiento BIGINT NOT NULL,

    CONSTRAINT pk_tarifa
        PRIMARY KEY (idtarifa),

    CONSTRAINT fk_tarifa_funcion
        FOREIGN KEY (idfuncion)
        REFERENCES funcion(idfuncion),

    CONSTRAINT fk_tarifa_asiento
        FOREIGN KEY (idasiento)
        REFERENCES asiento(idasiento),

    CONSTRAINT uq_tarifa_funcion_asiento
        UNIQUE (idfuncion, idasiento),

    CONSTRAINT chk_tarifa_precio
        CHECK (precio > 0)
);


-- 9. TIQUE

CREATE TABLE tique (
    idtique BIGINT GENERATED BY DEFAULT AS IDENTITY,
    codigo VARCHAR(50) NOT NULL,
    preciopagado DECIMAL(10,2) NOT NULL,
    fechaemision TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    estado VARCHAR(30) NOT NULL,
    idprecio BIGINT NOT NULL,
    idpago BIGINT NOT NULL,
    idusuario BIGINT NOT NULL,

    CONSTRAINT pk_tique
        PRIMARY KEY (idtique),

    CONSTRAINT uq_tique_codigo
        UNIQUE (codigo),

    CONSTRAINT uq_tique_tarifa
        UNIQUE (idprecio),

    CONSTRAINT fk_tique_tarifa
        FOREIGN KEY (idprecio)
        REFERENCES tarifa(idtarifa),

    CONSTRAINT fk_tique_pago
        FOREIGN KEY (idpago)
        REFERENCES pago(idpago),

    CONSTRAINT fk_tique_usuario
        FOREIGN KEY (idusuario)
        REFERENCES usuario(idusuario),

    CONSTRAINT chk_tique_precio
        CHECK (preciopagado > 0)
);


